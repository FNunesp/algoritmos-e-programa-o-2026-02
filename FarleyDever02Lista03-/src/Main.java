public class Main {
    public static void main(String[] args) {

        /*  Exercício 2 - Contagem regressiva para lançamento
        Crie um programa que faça uma contagem regressiva de 10 até 1. Ao final da contagem, imprima a mensagem: "Decolar!".
               Foco: Praticar o decremento de variável de controle (i--).


*/


        for (int i = 10; i >= 1; i--) {

            System.out.println("Contagem = " + i);
        }

        System.out.println("Decolar !");


    }
}